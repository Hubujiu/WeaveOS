// Synthetic B1 component evidence. Run with the isolated Vite fixture on 43121.
import {chromium,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
const evidence='docs/evidence/V010-020/q36';
const raw='.work/q36-record-raw';
await mkdir(evidence,{recursive:true});await mkdir(raw,{recursive:true});
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:1440,height:900},deviceScaleFactor:1,recordVideo:{dir:raw,size:{width:1440,height:900}}});
const page=await context.newPage();
await page.goto('http://127.0.0.1:43121/src/q36-front-fixture.html');
await page.evaluate(()=>document.fonts.ready);
await page.waitForTimeout(2500);
const trigger=page.getByRole('button',{name:/自定义筛选/});
const dialog=page.getByRole('dialog',{name:'自定义筛选'});
const settled=()=>page.waitForFunction(()=>!document.documentElement.classList.contains('q36-filter-transition-active'));
await trigger.click();await expect(dialog).toBeVisible();await settled();
await page.locator('.q36-filter-group-actions button').first().click();
await page.locator('.q36-filter-condition select').first().selectOption('account');
await page.locator('.q36-filter-condition input').first().fill('Alice');
await page.waitForTimeout(600);
await page.screenshot({path:`${evidence}/b1-filter-open-restored.png`});
await page.keyboard.press('Escape');await expect(dialog).not.toBeVisible();await settled();
await page.waitForTimeout(1200);
await page.screenshot({path:`${evidence}/b1-trigger-restored.png`});
await expect(trigger.locator('.q36-filter-trigger-content')).toHaveCSS('visibility','visible');
await trigger.click();await expect(dialog).toBeVisible();await settled();
await page.waitForTimeout(700);
await page.getByRole('heading',{name:'人员管理'}).click();
await expect(dialog).not.toBeVisible();await settled();await page.waitForTimeout(1200);
const video=page.video();await context.close();
if(video)await writeFile('.work/q36-restoration-recording.json',JSON.stringify({rawVideo:await video.path(),trimStartSeconds:1.5,output:`${evidence}/b1-filter-motion-restored.webm`},null,2));
await browser.close();
console.log('Recorded full initial state, native open/close, stable close >1s, reopen and outside close.');
